// Run against a disposable in-memory PostgreSQL with the path to @electric-sql/pglite as the first argument.
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
const { PGlite } = await import(pathToFileURL(process.argv[2]));
const db = new PGlite();
const c = "00000000-0000-4000-9000-000000000001", other = "00000000-0000-4000-9000-000000000004",
  m = "00000000-0000-4000-9000-000000000002", ordinary = "00000000-0000-4000-9000-000000000005",
  foreign = "00000000-0000-4000-9000-000000000006", z = "00000000-0000-4000-9000-000000000003";
await db.exec(`
create role anon; create role authenticated; create role service_role;
create schema private; create schema storage;
create table public.vereine(id uuid primary key);
create table public.schiedsrichter(id uuid primary key, verein_id uuid, name text, aktiv boolean);
create table storage.buckets(id text, name text, public boolean, file_size_limit integer, allowed_mime_types text[]);
create table storage.objects(bucket_id text, name text);
create function public.obmann_verein(p text) returns uuid language sql as $$ select case when p='adm' then '${c}'::uuid when p='adm2' then '${other}'::uuid end $$;
create function public.schiri_pin_pruefen(m uuid,p text) returns uuid language sql as $$ select verein_id from public.schiedsrichter where id=m and p='pin' $$;
insert into public.vereine values ('${c}'),('${other}');
insert into public.schiedsrichter values ('${m}','${c}','Tester',true),('${ordinary}','${c}','Mitglied',true),('${foreign}','${other}','Fremdverein',true);
insert into storage.objects values ('szenencheck-clips','${c}/${z}.mp4');
`);
const file = relative => readFileSync(new URL(relative,import.meta.url),"utf8");
await db.exec(file("../supabase/migrations/20261107125701_szenencheck_pilot.sql"));
await db.exec(file(process.argv[3] ?? "../supabase/migrations/20261124202109_szenencheck_runden_v2.sql"));
await db.exec("set role anon");
await assert.rejects(db.query("select public.szenencheck_gateway_v2('{}')"),{code:"42501"});
await db.exec("reset role; set role service_role");
await assert.rejects(db.query("select * from private.szenencheck_v2_stimmen"),{code:"42501"});
const api = async (aktion, extra={}, person=m) => (await db.query(
  "select public.szenencheck_gateway_v2($1::jsonb) as data",[JSON.stringify({aktion,person,pin:"pin",passwort:"adm",...extra})])).rows[0].data;
const date = (offset) => new Date(Date.now()+offset).toISOString();
const szenen = [{id:z,titel:"Ein Clip",kontext:"",art:"pfiff",feld:"Intern",datei:`${c}/${z}.mp4`}];
const vorlage = {titel:"Runde",typ:"reserve",beginn:date(600000),schluss:date(900000),szenen,tester:[],freigabe:false};
const normal = { ...vorlage, typ:"aktuell", tester:[m], vorschau:date(-60000) };
assert.equal((await api("v2-planen",{...normal,tester:[foreign]})).fehler,"tester");
for (let i=1;i<=4;i++) assert.ok((await api("v2-planen",{...vorlage,titel:"Reserve "+i})).id);
assert.deepEqual(await api("v2-laden",{},ordinary),{phase:"leer"});
const reserve=(await api("v2-verwaltung")).runden.find(r=>r.titel==="Reserve 1");
assert.equal((await api("v2-freigeben",{runde:reserve.id,sofort:false,beginn:date(9e6),schluss:date(1e7)})).ok,true);
const {id:runde}=await api("v2-planen",normal);
const v = {runde,szene:z};
assert.equal((await api("v2-laden")).phase,"test");
assert.equal((await api("v2-laden",{runde},foreign)).fehler,"runde");
assert.equal((await api("v2-video",v,ordinary)).fehler,"runde");
assert.equal((await api("v2-video",v)).pfad,`${c}/${z}.mp4`);
assert.equal((await api("v2-stimme",{...v,test:true,antwort:{pfiff:"foul"}})).ok,true);
assert.equal((await api("v2-freigeben",{runde,sofort:true})).ok,true);
assert.equal((await api("v2-planen",{...vorlage,typ:"aktuell",freigabe:true})).fehler,"ueberschneidung");
assert.equal((await api("v2-freigeben",{runde,sofort:true})).fehler,"fest");
assert.equal((await api("v2-stimme",{...v,test:true,antwort:{pfiff:"foul"}})).fehler,"phase");
let stand=await api("v2-laden");
assert.equal(stand.phase,"offen");
assert.deepEqual(stand.stimmen,{});
assert.equal(stand.szenen[0].feld,undefined);
assert.equal(stand.szenen[0].datei,undefined);
const next=await api("v2-planen",{...normal,titel:"Nächste Vorschau",beginn:date(2e6),schluss:date(3e6)});
assert.deepEqual((await api("v2-laden")).vorschauen.map(r=>r.id),[next.id]);
assert.deepEqual((await api("v2-laden",{},ordinary)).vorschauen,[]);
assert.equal((await api("v2-laden",{runde:next.id})).phase,"test");
assert.equal((await api("v2-pause",{runde,pausiert:true})).ok,true);
assert.equal((await api("v2-laden",{runde},ordinary)).phase,"pausiert");
assert.equal((await api("v2-video",v)).fehler,"geschlossen");
assert.equal((await api("v2-pause",{runde,pausiert:false})).ok,true);
assert.equal((await api("v2-stimme",{...v,test:false,antwort:{pfiff:"weiterspielen"}},ordinary)).ok,true);
assert.equal((await api("v2-einordnen",{runde,sofort:true,einordnungen:{}})).fehler,"noch_offen");
await db.exec("reset role");
await assert.rejects(db.query(
  "insert into private.szenencheck_runden(verein_id,titel,beginn,schluss,szenen) values($1,'Pilot',now(),now()+interval '2 min',$2)",
  [c,JSON.stringify(szenen)]),{code:"23P01"});
await db.query("update private.szenencheck_v2_runden set beginn=now()-interval '2 minutes',schluss=now()-interval '1 minute' where id=$1",[runde]);
await db.exec("set role service_role");
assert.equal((await api("v2-laden",{runde})).phase,"geschlossen");
assert.equal((await api("v2-einordnen",{runde,sofort:true,einordnungen:{[z]:{text:"Nachbesprechung",quelle:"https://www.dfb.de"}}})).ok,true);
stand=await api("v2-laden",{runde});
assert.equal(stand.phase,"recap");
assert.equal(stand.szenen[0].feld,"Nachbesprechung");
assert.deepEqual(stand.recap[z],[{antwort:{pfiff:"weiterspielen"},anzahl:1}]);
assert.equal((await api("v2-einordnen",{runde,sofort:true,einordnungen:{}})).fehler,"fest");
assert.ok(!(await api("v2-verwaltung")).tester.some(t=>t.id===foreign));
assert.ok((await api("v2-verwaltung",{testpasswort:"adm2"})).tester.some(t=>t.id===foreign && t.extern));
assert.equal((await api("v2-verwaltung",{testpasswort:"falsch"})).fehler,"zugang");
const {id:andere}=await api("v2-planen",{...normal,tester:[foreign],testpasswort:"adm2",beginn:date(5e6),schluss:date(6e6)});
assert.equal((await api("v2-laden",{runde:andere},foreign)).phase,"test");
assert.equal((await api("v2-stimme",{runde:andere,szene:z,test:true,antwort:{pfiff:"foul"}},foreign)).ok,true);
assert.equal((await api("v2-freigeben",{runde:andere,sofort:true})).ok,true);
assert.equal((await api("v2-laden",{runde:andere},foreign)).fehler,"runde");
assert.equal((await api("v2-video",{runde:andere,szene:z},foreign)).fehler,"runde");
await db.close();
console.log("Szenencheck: lokale PostgreSQL-Prüfung bestanden");
